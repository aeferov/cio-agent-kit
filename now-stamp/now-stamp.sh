#!/usr/bin/env bash
# UserPromptSubmit-хук: штамп текущего времени в КАЖДУЮ реплику пользователя.
#
# Зачем: у ассистента нет часов. Дата приходит в системном контексте, а времени
# там нет вообще — узнать его можно только запустив `date`. Между репликами
# проходит произвольный интервал: попрощались в 00:17, следующий вопрос в 10:42,
# и без штампа модель считает, что это тот же момент разговора.
#
# Время доставляется СОБЫТИЕМ (каждая реплика), а не памятью и не дисциплиной
# «не забудь спросить date».
#
# Вывод хука попадает в контекст модели перед обработкой реплики.
set -uo pipefail

TZ_HOME="${NOW_STAMP_TZ_HOME:-Europe/Moscow}"
TZ_ALT="${NOW_STAMP_TZ_ALT:-}"          # вторая зона, если работаем не дома

line="— сейчас: $(TZ="$TZ_HOME" date '+%H:%M %Z, %A %d.%m.%Y')"

# Вторая зона показывается, только если она задана И отличается по смещению —
# иначе строка-дубль («в Турции 10:42, в Москве 10:42») лишь засоряет контекст.
if [ -n "$TZ_ALT" ]; then
  off_home=$(TZ="$TZ_HOME" date +%z)
  off_alt=$(TZ="$TZ_ALT" date +%z)
  if [ "$off_home" != "$off_alt" ]; then
    line="$line · $(TZ="$TZ_ALT" date '+%H:%M %Z')"
  fi
fi

echo "$line"
